# OTA password kept out of the project configuration.
#
# ${sysenv.OTA_PASSWORD_...} in platformio.ini goes into project.checksum — a different
# value (e.g. a shell without ~/.secrets/iot.env) makes PlatformIO wipe the whole
# .pio/build and rebuild both environments. Here the password goes into a generated
# header (a change rebuilds only main.cpp) and into the espota flags; the compiler
# flags and the checksum stay constant.
#
# Variable name: custom_ota_password_var in platformio.ini (named after the device IP,
# shared ~/.secrets/iot.env). Fixed for this single device, also for OTA: an upload to
# another IP sends this device's password and is rejected there — no wrong-device flash.
# Upload without the variable = error (USB too — the device would get an empty password,
# i.e. OTA open to anyone on the network); build only = warning.

import os

Import("env")

var = env.GetProjectOption("custom_ota_password_var")
password = os.environ.get(var, "")
uploading = any(t in COMMAND_LINE_TARGETS for t in ("upload", "uploadfs"))

if not password:
    if uploading:
        print("\n*** %s not set — upload aborted (source ~/.secrets/iot.env)\n" % var)
        env.Exit(1)
    print("*** WARNING: %s not set — firmware with an empty OTA password (build only)" % var)

gen_dir = os.path.join(env.subst("$BUILD_DIR"), "generated")
header = os.path.join(gen_dir, "ota_secret.h")
escaped = password.replace("\\", "\\\\").replace('"', '\\"')
content = '#pragma once\n// Generated by scripts/ota_secret.py — do not edit\n#define OTA_PASSWORD "%s"\n' % escaped

# Write only on change — a constant mtime means no main.cpp recompile
old = None
if os.path.isfile(header):
    with open(header, encoding="utf8") as f:
        old = f.read()
if old != content:
    os.makedirs(gen_dir, exist_ok=True)
    with open(header, "w", encoding="utf8") as f:
        f.write(content)

env.Append(CPPPATH=[gen_dir])

if env.subst("$UPLOAD_PROTOCOL") == "espota" and password:
    env.Append(UPLOAD_FLAGS=["--auth=" + password])

    # The platform adds espota --debug (after pre-scripts), which prints all options,
    # the password included — drop it right before the upload
    def _no_espota_debug(source, target, env):
        env.Replace(UPLOADERFLAGS=[f for f in env.get("UPLOADERFLAGS", []) if f != "--debug"])

    env.AddPreAction("upload", _no_espota_debug)
