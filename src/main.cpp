static uint32_t g_restartAtTs = 0;  // restart target time (local midnight); 0 = disabled

// A planned restart waits while the pump runs, an ATO cycle, a manual session or
// a calibration is in progress (a cut cycle would miss the 24 h counter and the
// history) and in Service Mode (the user may be servicing the aquarium — a restart
// would bring Auto back)
static bool isRestartBlocked() {
    return isPumpActive() || waterAlgorithm.isInCycle() || isDirectPumpMode() ||
           isPumpCalibrationActive() || isSystemDisabled();
}

void setup() {
   
    delay(2000); // Wait for serial monitor

    initBuzzer();
    buzzerPowerOn();

    // Initialize core systems
    initLogging();

    LOG_INFO("");
    LOG_INFO("====================================");
    LOG_INFO("=== ESP32-C3 Water System Starting ===");
    LOG_INFO("Single Mode - Captive Portal Provisioning");
    LOG_INFO("ESP32 Flash size: %d", ESP.getFlashChipSize());
    LOG_INFO("Free heap: %d", ESP.getFreeHeap());
    LOG_INFO("CHECKING PROVISIONING BUTTON");

    // Check if provisioning button is held
    if (checkProvisioningButton()) {
        LOG_INFO("");
        LOG_INFO("====================================");
        LOG_INFO("    ENTERING PROVISIONING MODE");
        LOG_INFO("====================================");
        LOG_INFO("Initializing FRAM for credential storage");

        Wire.begin(I2C_SDA_PIN, I2C_SCL_PIN);
        Wire.setClock(100000);
        delay(50);  // ESP32-S3 I2C needs settling time after Wire.begin()

        if (!initFRAM()) {
            LOG_INFO("WARNING: FRAM initialization failed!");
            LOG_INFO("Credentials may not be saved properly");
            buzzerCritical();
            delay(2000);
        } else {
            LOG_INFO("");
            LOG_INFO("FRAM ready");
        }

        if (!startAccessPoint()) {
            LOG_INFO("");
            LOG_INFO("FATAL: Failed to start AP - halting");
            while(1) delay(1000);
        }
        
        // Start DNS Server for captive portal
        if (!startDNSServer()) {
            LOG_INFO("");
            LOG_INFO("FATAL: Failed to start DNS - halting");
            while(1) delay(1000);
        }
        
        LOG_INFO("");
        LOG_INFO("====================================");
        LOG_INFO("=== PROVISIONING MODE ACTIVE ===");
        LOG_INFO("Connect to WiFi network:");
        LOG_INFO("SSID: ESP32-WATER-SETUP");
        LOG_INFO("Password: setup12345");
        LOG_INFO("URL: http://");
        LOG_INFO("%s", getAPIPAddress().toString());

        // Start Web Server
        if (!startWebServer()) {
            Serial.println("FATAL: Failed to start web server - halting");
            while(1) delay(1000);
        }
        
        LOG_INFO("");
        LOG_INFO("=== CAPTIVE PORTAL READY ===");
        LOG_INFO("Open a browser or wait for captive portal popup");

        buzzerOK();

        // Enter blocking loop - never returns
        runProvisioningLoop();
        
        // This line will never be reached
    }
    
    // === PRODUCTION MODE SETUP ===
    LOG_INFO("");
    LOG_INFO("=== Production Mode - Full Water System ===");

    initWaterSensor();
    initPumpController();

    Wire.begin(I2C_SDA_PIN, I2C_SCL_PIN);  // Init I2C before FRAM
    Wire.setClock(100000);


    delay(2000);

    // RTC before initFromFRAM — scanRolling24h() needs a valid getUnixTimestamp()
    initializeRTC();

    initNVS();          // initNVS() calls initFRAM() internally (config.cpp)
    loadVolumeFromNVS();
    waterAlgorithm.initFromFRAM();
    initReservoirConfig();
    initReserveController();
    // I2C bus reset after burst ring-buffer reads — ensures clean state for credentials and RTC.
    Wire.end();
    delay(10);
    Wire.begin(I2C_SDA_PIN, I2C_SCL_PIN);
    Wire.setClock(100000);
    delay(10);
    framReconnect();
    initLevelEventLog();
    initLevelSensor();

    bool credentials_loaded = initCredentialsManager();
    LOG_INFO("");
    if (credentials_loaded) {
        LOG_INFO("Device ID: %s", getDeviceID());
    } else {
        LOG_INFO("FALLBACK_MODE");
    }
    initWiFi();
    delay(2000);

    LOG_INFO("");
    LOG_INFO("====================================");
    LOG_INFO("Initializing network...");
    LOG_INFO("[INIT] Initializing RTC...");
    LOG_INFO("RTC Status: %s", getRTCInfo().c_str());
    LOG_INFO("[INIT] Waiting for RTC to stabilize...");
    LOG_INFO("====================================");
    
    if (!isRTCWorking()) {
        LOG_WARNING("⚠️ WARNING: RTC not working properly");
        LOG_WARNING("⚠️ Daily volume tracking may be affected");
        LOG_WARNING("");
    }
    // Initialize security
    initAuthManager();
    initSessionManager();
    initRateLimiter();
    
    // Initialize VPS logger
    // initVPSLogger();
    
    // Initialize web server
    initWebServer();
    
    // Post-init diagnostics
    Serial.println();
    LOG_INFO("");
    LOG_INFO("====================================");
    LOG_INFO("SYSTEM POST-INIT STATUS");
    LOG_INFO("RTC Working: %s", isRTCWorking() ? "YES" : "NO");
    LOG_INFO("RTC Info: %s", getRTCInfo().c_str());
    LOG_INFO("Current Time: %s", getCurrentTimestamp().c_str());
    LOG_INFO("Water Algorithm:");
    LOG_INFO("  State: %s", waterAlgorithm.getStateString());
    LOG_INFO("  Rolling 24h: %d ml", waterAlgorithm.getRolling24hVolume());
    LOG_INFO("  Dose: %d ml, daily limit: %d ml", waterAlgorithm.getConfig().dose_ml, waterAlgorithm.getConfig().daily_limit_ml);
    LOG_INFO("  EMA bootstrap: %d rate=%.2f score=%.2f",
             waterAlgorithm.getEma().bootstrap_count,
             waterAlgorithm.getEma().ema_rate_ml_h,
             waterAlgorithm.getEma().alarm_score);
    
    if (isWiFiConnected()) {
        LOG_INFO("Dashboard: http://");
        LOG_INFO("%s", getLocalIP().toString());

        ArduinoOTA.setPassword(OTA_PASSWORD);
        ArduinoOTA.onStart([]() {
            // CRITICAL: stop the pump BEFORE the flash erase — the erase blocks the
            // CPU for longer than one tick, so a pump left ON would stay ON for
            // the whole OTA.
            LOG_INFO("OTA update starting — stopping pump and disabling system");
            if (isPumpActive()) stopPump();
            setSystemState(false);
        });
        ArduinoOTA.onEnd([]() {
            LOG_INFO("OTA update complete — restarting");
        });
        ArduinoOTA.onError([](ota_error_t error) {
            // OTA may fail for reasons other than a crash (bad hash, network) —
            // the device does not restart by itself then.
            LOG_ERROR("OTA error [%u] — re-enabling system", error);
            setSystemState(true);
        });
        ArduinoOTA.begin();
        LOG_INFO("OTA ready");
    }
    // Listens regardless of WiFi state — accepts clients once WiFi (re)connects
    startNetworkLog();
    LOG_INFO("Current Time: %s", getCurrentTimestamp().c_str());
    LOG_INFO("=== System initialization complete ===");
    LOG_INFO("====================================");

    // Critical hardware check (FRAM, RTC) — latched alarm, see hw_health.h
    initHwHealth();

    // Boot-complete beep — CRITICAL if anything critical is not working
    bool bootOk = !getHwFaultActive() && credentials_loaded && isWiFiConnected();
    if (bootOk) {
        buzzerOK();
    } else {
        buzzerCritical();
    }

    // Restart target time = the next local midnight
    // Guard: the RTC must work and have a sane time (year > 2020)
    uint32_t nowTs = (uint32_t)getUnixTimestamp();
    struct tm t;
    time_t ts = (time_t)nowTs;
    localtime_r(&ts, &t);
    if (isRTCWorking() && t.tm_year > 120) {  // tm_year: years since 1900; 120 = 2020
        uint32_t secOfDay = t.tm_hour * 3600 + t.tm_min * 60 + t.tm_sec;
        uint32_t midnight = nowTs - secOfDay + 86400UL;  // next local midnight (UTC)
        g_restartAtTs = midnight;
        LOG_INFO("Daily restart scheduled at next midnight (ts=%lu, in %lus)", midnight, midnight - nowTs);
    } else {
        g_restartAtTs = 0;  // fallback: restart disabled (no RTC)
        LOG_WARNING("RTC not ready — daily midnight restart disabled");
    }
}

void loop() {
    // Production mode loop - full water system
    static unsigned long lastUpdate = 0;
    unsigned long now = millis();

    // DAILY RESTART CHECK — at local midnight (00:00)
    // Guard: min uptime 30 min (no restart loop when booted just before midnight).
    // Postponed while isRestartBlocked()
    if (g_restartAtTs > 0 && now > 1800000UL) {
        uint32_t nowTs = (uint32_t)getUnixTimestamp();
        bool busy = isRestartBlocked();
        static bool deferLogged = false;
        if (nowTs >= g_restartAtTs && busy && !deferLogged) {
            deferLogged = true;
            LOG_INFO("Daily restart postponed — pump / cycle / manual session / calibration / Service Mode");
        }
        if (nowTs >= g_restartAtTs && !busy) {
            Serial.println("=== DAILY RESTART: midnight reached ===");

            if (isPumpActive()) stopPump();
            delay(1000);

            Serial.println("System restarting in 3 seconds...");
            delay(3000);
            ESP.restart();
        }
    }
    
    // FRAM missing at boot answers again — restart re-inits it (data from FRAM)
    updateHwHealth();
    if (isHwRecoveryRestartWanted() && !isRestartBlocked()) {
        noteHwRecoveryRestart();
        if (isPumpActive()) stopPump();
        delay(1000);
        ESP.restart();
    }

    // OTA — must be called every loop() iteration, not in the slower tick
    ArduinoOTA.handle();
    handleNetworkLog();

    // Sensor + algorithm — every loop iteration
    updateWaterSensor();
    updateLevelSensor();
    updateReserveController();
    updatePumpCalibration();
    updateLevelTest();
    waterAlgorithm.update();

    // Other systems every 100 ms
    if (now - lastUpdate >= 100) {
        updatePumpController();

        // Buzzer — critical only: every ATO error (state stays until reset from the
        // GUI), the reservoir alarm level, 24 h without a top-off and a FRAM / RTC
        // fault; the reserve range is GUI-only
        if (isReserveEmpty() || waterAlgorithm.getState() == STATE_ERROR ||
            waterAlgorithm.isNoTopOffAlarm() || isHwFaultAlarm()) {
            setBuzzerMode(BUZZER_ALARM);
        } else {
            setBuzzerMode(BUZZER_OFF);
        }

        updateSessionManager();
        updateRateLimiter();
        updateWiFi();
        lastUpdate = now;
    }

    delay(100);
}